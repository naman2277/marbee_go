#!/usr/bin/env node
// Bundle an edge function + its relative imports (e.g. ../_shared/*.ts) into ONE file
// for pasting into the Supabase dashboard editor. Output: supabase/web-deploy/<name>.ts
//
//   node scripts/bundle-edge-function.mjs events-ingest push-subscribe ...
//
// Rules: relative imports are inlined once (dependency order) with `export` removed;
// external URL imports are merged per URL; all supabase-js URLs are normalised to one
// pinned version so shared modules don't import two copies.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FN_DIR = resolve(ROOT, 'supabase/functions');
const OUT_DIR = resolve(ROOT, 'supabase/web-deploy');
const SUPABASE_JS = 'https://esm.sh/@supabase/supabase-js@2.45.4';
const IMPORT_RE = /^import\s+(type\s+)?\{([^}]*)\}\s+from\s+['"]([^'"]+)['"];?\s*$/;

function normaliseUrl(url) {
  return /^https:\/\/esm\.sh\/@supabase\/supabase-js@/.test(url) ? SUPABASE_JS : url;
}

function bundle(name) {
  const entry = resolve(FN_DIR, name, 'index.ts');
  if (!existsSync(entry)) throw new Error(`No function at ${entry}`);

  const externals = new Map(); // url -> Map(specifier -> isTypeOnly)
  const included = new Set();
  const chunks = [];

  function addExternal(url, specs, wholeIsType) {
    const key = normaliseUrl(url);
    const map = externals.get(key) ?? new Map();
    for (const raw of specs.split(',').map((s) => s.trim()).filter(Boolean)) {
      const isType = wholeIsType || raw.startsWith('type ');
      const spec = raw.replace(/^type\s+/, '');
      // a value import wins over a type-only import of the same name
      map.set(spec, (map.get(spec) ?? true) && isType);
    }
    externals.set(key, map);
  }

  function visit(file, isEntry) {
    if (included.has(file)) return;
    included.add(file);
    const lines = readFileSync(file, 'utf8').replace(/\r\n/g, '\n').split('\n');
    const body = [];
    for (const line of lines) {
      const m = line.match(IMPORT_RE);
      if (m) {
        const [, typeKw, specs, from] = m;
        if (from.startsWith('.')) visit(resolve(dirname(file), from), false);
        else addExternal(from, specs, Boolean(typeKw));
        continue;
      }
      if (/^import\s/.test(line)) throw new Error(`Unsupported import form in ${file}: ${line}`);
      body.push(isEntry ? line : line.replace(/^export\s+(?=(async\s+)?function|const|let|class|type|interface)/, ''));
    }
    chunks.push(`// ---- ${relative(FN_DIR, file).replace(/\\/g, '/')} ${'-'.repeat(Math.max(4, 70 - file.length % 40))}\n${body.join('\n').trim()}\n`);
  }

  visit(entry, true);

  const importLines = [...externals.entries()].map(([url, map]) => {
    const specs = [...map.entries()].map(([s, t]) => (t ? `type ${s}` : s)).join(', ');
    return `import { ${specs} } from '${url}';`;
  });

  const header = [
    `// AUTO-GENERATED by scripts/bundle-edge-function.mjs — do not edit by hand.`,
    `// Source of truth: supabase/functions/${name}/ (+ inlined _shared modules).`,
    `// Deploy: Supabase Dashboard → Edge Functions → ${name} → paste → Deploy.`,
    '',
  ];
  const out = [...header, ...importLines, '', ...chunks].join('\n');
  const target = resolve(OUT_DIR, `${name}.ts`);
  writeFileSync(target, out);
  console.log(`bundled ${name} → ${relative(ROOT, target).replace(/\\/g, '/')} (${included.size} module(s))`);
}

const names = process.argv.slice(2);
if (!names.length) {
  console.error('usage: node scripts/bundle-edge-function.mjs <function-name> [...]');
  process.exit(1);
}
for (const n of names) bundle(n);
